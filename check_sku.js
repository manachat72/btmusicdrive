const products = JSON.parse(fs.readFileSync('products.json', 'utf8'));

let results = [];
let fixes = [];

for (const input of inputList) {
    const cleanName = input.name.trim();
    const currentSku = input.sku.trim();
    
    let targetSku = null;
    const exact = products.find(p => p.name.trim() === cleanName);
    if (exact) {
        targetSku = exact.sku;
    } else {
        const fuzzy = products.find(p => cleanName.includes(p.name.trim()) || p.name.trim().includes(cleanName));
        if (fuzzy) targetSku = fuzzy.sku;
    }
    
    if (targetSku) {
        if (currentSku !== targetSku) {
            fixes.push({id: input.id, name: cleanName, old: currentSku, new: targetSku});
        } else {
            results.push(`? [${input.id}] ถูกต้องแล้ว: ${currentSku}`);
        }
    } else {
        results.push(`?? [${input.id}] ไม่พบข้อมูลในระบบ: ${cleanName}`);
    }
}

let md = '### รายการที่ต้องแก้ไข SKU (เนื่องจาก SKU ปัจจุบันผิด)\n\n';
md += '| Product ID | ชื่อสินค้า | SKU ผิด | SKU ที่ถูกต้อง |\n';
md += '|---|---|---|---|\n';
for (const f of fixes) {
    md += `| ${f.id} | ${f.name} | \`${f.old}\` | **\`${f.new}\`** |\n`;
}

md += '\n\n### รายการที่ถูกต้องอยู่แล้ว\n\n';
for (const r of results) {
    if (r.startsWith('?')) md += `- ${r}\n`;
}

md += '\n\n### รายการที่ไม่พบข้อมูล\n\n';
for (const r of results) {
    if (r.startsWith('??')) md += `- ${r}\n`;
}

